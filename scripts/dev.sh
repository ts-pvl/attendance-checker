#!/usr/bin/env bash
# Run the whole system locally: server, admin UI, QR page and a simulated
# lab PC (PC-01 = this machine). Safe to run again; setup happens once.
#
#   make dev                                        # without Telegram
#   BOT_TOKEN=123:abc BOT_USERNAME=MyTestBot make dev   # with a test bot
#
# State lives in .dev/ (git-ignored). Delete it to start from scratch.
# Development only: the admin password is printed and stored in plain text.
set -euo pipefail

cd "$(dirname "$0")/.."
DIR="$PWD/.dev"
BIN="$PWD/dist/attendance"
PORT="${PORT:-8080}"
ADMIN_PASSWORD="${ADMIN_PASSWORD:-dev-password-123}"
CONF="$DIR/attendance.conf"

mkdir -p "$DIR"
[[ -x "$BIN" ]] || { echo "build first: make build" >&2; exit 1; }

if [[ ! -f "$DIR/host_key" ]]; then
  "$BIN" gen-key > "$DIR/host_key"
fi

BOT_LINES="bot_username = ${BOT_USERNAME:-YourTestBot}"
if [[ -n "${BOT_TOKEN:-}" ]]; then
  (umask 077; printf '%s\n' "$BOT_TOKEN" > "$DIR/bot_token")
  BOT_LINES+=$'\n'"bot_token_file = $DIR/bot_token"
fi

# Under WSL 2 (NAT networking) a browser on Windows reaches the server through
# the WSL address and arrives from the Windows host, which is the default
# gateway. Listen on all interfaces and let only that one address into admin.
LISTEN="127.0.0.1"
ADMIN_NETS="127.0.0.0/8, ::1/128"
WSL_IP="" WIN_HOST=""
if grep -qi microsoft /proc/sys/kernel/osrelease 2>/dev/null; then
  read -r WIN_HOST DEV < <(ip route show default 2>/dev/null | awk '/^default/ {print $3, $5; exit}') || true
  [[ -n "${DEV:-}" ]] && WSL_IP=$(ip -4 -o addr show dev "$DEV" scope global 2>/dev/null | awk '{sub(/\/.*/, "", $4); print $4; exit}')
  if [[ -n "$WIN_HOST" && -n "$WSL_IP" ]]; then
    LISTEN="0.0.0.0"
    ADMIN_NETS+=", $WIN_HOST/32"
  fi
fi
# The simulated PC-01 is this machine, or the Windows host under WSL (its
# events are then sent with Windows curl.exe, so they come from that address).
PC_IP=127.0.0.1 CURL=curl NULL=/dev/null SERVER_IP=127.0.0.1
WIN_CURL=$(command -v curl.exe 2>/dev/null || echo /mnt/c/Windows/System32/curl.exe)
if [[ "$LISTEN" == 0.0.0.0 && -x "$WIN_CURL" ]]; then
  PC_IP=$WIN_HOST CURL=$WIN_CURL NULL=NUL SERVER_IP=$WSL_IP
fi
printf 'name,ip\nPC-01,%s\n' "$PC_IP" > "$DIR/hosts.csv"

cat > "$CONF" <<EOF
# Generated by scripts/dev.sh — local development only.
listen = $LISTEN:$PORT
db = $DIR/attendance.db
$BOT_LINES
host_key_file = $DIR/host_key
hosts_file = $DIR/hosts.csv
token_secret_file = $DIR/token_secret
backup_dir = $DIR/backups
admin_networks = $ADMIN_NETS
# PC-01 is also the admin browser here.
admin_from_lab_pcs = true
EOF

if ! "$BIN" user list -config "$CONF" | grep -q '^admin '; then
  printf '%s\n' "$ADMIN_PASSWORD" | "$BIN" user add admin -role admin -config "$CONF" >/dev/null 2>&1
fi
if [[ "$("$BIN" students list -config "$CONF" | wc -l)" -le 1 && -f deploy/students.csv.example ]]; then
  "$BIN" students import deploy/students.csv.example -config "$CONF" >/dev/null
fi

NOBOT=(-no-bot)
[[ -n "${BOT_TOKEN:-}" ]] && NOBOT=()
"$BIN" serve "${NOBOT[@]}" -config "$CONF" &
SERVER=$!

# Simulated PC agent for PC-01: a login, then a heartbeat every minute.
fake_pc() {
  local key url="http://$SERVER_IP:$PORT/event"
  key=$(cat "$DIR/host_key")
  # The key goes to curl on stdin, never on the command line.
  send() { printf 'header = "X-Host-Key: %s"\n' "$key" | "$CURL" -fsS -o "$NULL" --config - -d sid=dev-pc01 "$@" "$url" 2>/dev/null; }
  until send -d kind=session_start; do sleep 0.5; done
  while sleep 60; do
    send -d kind=heartbeat -d idle_ms=0 || true
  done
}
fake_pc &
PC=$!
trap 'pkill -P $PC 2>/dev/null; kill $PC $SERVER 2>/dev/null; wait $SERVER 2>/dev/null' EXIT INT TERM

TG="disabled (set BOT_TOKEN and BOT_USERNAME to enable)"
[[ -n "${BOT_TOKEN:-}" ]] && TG="enabled as @${BOT_USERNAME:-YourTestBot}"

WHO="this machine plays PC-01"
[[ "$PC_IP" != 127.0.0.1 ]] && WHO="WSL detected: open these in the Windows browser, which plays PC-01"

sleep 1
cat <<EOF

  Admin UI   http://$SERVER_IP:$PORT/admin   (user: admin, password: $ADMIN_PASSWORD)
  QR page    http://$SERVER_IP:$PORT/qr      ($WHO)
  Telegram   $TG

  Press Ctrl+C to stop. Data stays in .dev/; delete it to start over.

EOF
wait $SERVER
